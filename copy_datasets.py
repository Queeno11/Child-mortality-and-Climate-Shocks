"""Copy the key datasets needed by the ``main.py`` pipeline to a new project folder.

The full ``Data/`` tree is ~130 GB, most of which is obsolete intermediate
versions. This script copies only the files the current pipeline actually
reads, preserving the ``Data/Data_in|Data_proc|Data_out`` layout so the scripts
keep working unchanged in the new location.

Nothing is ever moved or deleted: every transfer is a plain copy (``copy2``,
so timestamps are preserved).

Tiers
-----
``core``      Inputs of the scripts currently enabled in ``main.py``'s
              PIPELINE (03 -> 04 -> 06).  ~7.3 GB.
``resume``    The merged feather produced by ``03_merge_climate_and_DHS.py``.
              Copy it if you want to skip step 03 and start at the Julia
              regressions.  ~1.9 GB.
``upstream``  Inputs of ``02_assign_shocks_to_DHS.py`` and
              ``02b_assign_climatic_bands.py`` (commented out of the PIPELINE
              but needed to regenerate the ``core`` Data_proc files).  ~11 GB.
``outputs``   The LaTeX regression tables in ``Outputs/`` that
              ``06_charts.py`` reads.  Only needed if you want to plot without
              re-running ``04_regressions.jl``.  A few MB.

Usage
-----
    # See what would be copied, with sizes, and copy nothing:
    python copy_datasets.py --dest "D:/New Project" --dry-run

    # Copy the minimum needed to run the current pipeline end to end:
    python copy_datasets.py --dest "D:/New Project"

    # Everything (also lets you re-run 02/02b and plot without Julia):
    python copy_datasets.py --dest "D:/New Project" --tier core resume upstream outputs

Already-present destination files with a matching size are skipped, so the
script is safe to re-run / resume after an interruption.
"""

from __future__ import annotations

import argparse
import os
import shutil
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent

try:  # optional: lets the EXTERNAL_ENV_VARS entries resolve from the project .env
    from dotenv import load_dotenv

    load_dotenv(PROJECT_ROOT / ".env")
except ImportError:
    pass

# --- Manifest -----------------------------------------------------------------
# Each entry: (tier, path relative to the project root, what uses it).
# Paths are relative so the same layout is recreated under --dest.
MANIFEST = [
    # ---- core: inputs of the currently enabled pipeline (03, 04, 06) --------
    (
        "core",
        "Data/Data_in/DHS/DHSBirthsGlobalAnalysis_07272025.dta",
        "03: DHS births microdata (also read by 02 and 02b)",
    ),
    (
        "core",
        "Data/Data_in/WB Country Classification/wb_country_classification.xlsx",
        "03: World Bank income-group lookup",
    ),
    (
        "core",
        "Data/Data_proc/ClimateShocks_assigned_v11_full.parquet",
        "03: climate shocks assigned to each birth (output of 02)",
    ),
    (
        "core",
        "Data/Data_proc/DHSBirthsGlobalAnalysis_07272025_climate_bands_assigned.parquet",
        "03: Koppen bands + RWI + country indices per household (output of 02b)",
    ),
    # ---- resume: skip step 03 ----------------------------------------------
    (
        "resume",
        "Data/Data_out/DHSBirthsGlobal&ClimateShocks_v11_full.feather",
        "04: merged analysis dataset (regenerated by 03, copy to skip it)",
    ),
    # ---- upstream: inputs of 02 / 02b --------------------------------------
    (
        "upstream",
        "Data/Data_out/Climate_shocks_v11.nc",
        "02: gridded climate shock indices (output of 01)",
    ),
    (
        "upstream",
        "Data/Data_in/relative-wealth-index-april-2021",
        "02b: Meta Relative Wealth Index, one CSV per country",
    ),
    (
        "upstream",
        "Data/Data_in/ND Gain Index 2025/resources/gain/gain.csv",
        "02b: ND-GAIN country index",
    ),
    (
        "upstream",
        "Data/Data_in/worldriskindex-2024.xlsx",
        "02b: World Risk Index 2024",
    ),
]

# Regression tables consumed by 06_charts.py. Copied as a glob because the exact
# file names depend on the --spi/--temp/--stat/--timeframe combination used.
OUTPUT_GLOBS = [
    ("outputs", "Outputs", "*.tex", "06: regression tables (output of 04)"),
    ("outputs", "Outputs/heterogeneity", "**/*.tex", "06: heterogeneity tables (output of 04)"),
]

# External datasets whose location lives in .env (see paths.py / .env.example).
# They are copied into Data/External/<var name>/ in the new project; remember to
# point the new .env at the copies afterwards.
EXTERNAL_ENV_VARS = [
    ("upstream", "CLIMATE_BANDS", "02b: Koppen-Geiger climate classification grid"),
]

ALL_TIERS = ["core", "resume", "upstream", "outputs"]
DEFAULT_TIERS = ["core", "resume"]


# --- Helpers ------------------------------------------------------------------
def human_size(num_bytes):
    """Format a byte count as a short human-readable string."""
    size = float(num_bytes)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if size < 1024 or unit == "TB":
            return f"{size:.1f} {unit}" if unit != "B" else f"{int(size)} B"
        size /= 1024
    return f"{size:.1f} TB"


def path_size(path):
    """Total size in bytes of a file, or of every file under a directory."""
    path = Path(path)
    if path.is_file():
        return path.stat().st_size
    if path.is_dir():
        return sum(p.stat().st_size for p in path.rglob("*") if p.is_file())
    return 0


def iter_files(source):
    """Yield (absolute file, path relative to ``source``'s parent) for a file or dir."""
    source = Path(source)
    if source.is_file():
        yield source, Path(source.name)
    elif source.is_dir():
        for item in sorted(source.rglob("*")):
            if item.is_file():
                yield item, item.relative_to(source.parent)


def build_jobs(tiers, project_root=PROJECT_ROOT, dest_root=None):
    """Return the list of copy jobs for the requested tiers.

    A job is a dict with ``source``, ``dest``, ``relative``, ``tier``, ``note``
    and ``exists``. Missing sources are kept in the list (``exists=False``) so
    they can be reported instead of silently ignored.
    """
    project_root = Path(project_root)
    dest_root = Path(dest_root) if dest_root is not None else None
    jobs = []

    for tier, relative, note in MANIFEST:
        if tier not in tiers:
            continue
        source = project_root / relative
        jobs.append(
            {
                "tier": tier,
                "note": note,
                "source": source,
                "relative": Path(relative),
                "dest": (dest_root / relative) if dest_root else None,
                "exists": source.exists(),
            }
        )

    for tier, subdir, pattern, note in OUTPUT_GLOBS:
        if tier not in tiers:
            continue
        base = project_root / subdir
        if not base.is_dir():
            jobs.append(
                {
                    "tier": tier,
                    "note": note,
                    "source": base,
                    "relative": Path(subdir),
                    "dest": (dest_root / subdir) if dest_root else None,
                    "exists": False,
                }
            )
            continue
        for match in sorted(base.glob(pattern)):
            if not match.is_file():
                continue
            relative = match.relative_to(project_root)
            jobs.append(
                {
                    "tier": tier,
                    "note": note,
                    "source": match,
                    "relative": relative,
                    "dest": (dest_root / relative) if dest_root else None,
                    "exists": True,
                }
            )

    for tier, var, note in EXTERNAL_ENV_VARS:
        if tier not in tiers:
            continue
        value = os.getenv(var)
        if not value:
            jobs.append(
                {
                    "tier": tier,
                    "note": f"{note} [env var {var} not set - skipped]",
                    "source": None,
                    "relative": Path("Data/External") / var,
                    "dest": None,
                    "exists": False,
                }
            )
            continue
        source = Path(value)
        relative = Path("Data/External") / var / source.name
        jobs.append(
            {
                "tier": tier,
                "note": f"{note} [from env var {var}]",
                "source": source,
                "relative": relative,
                "dest": (dest_root / relative) if dest_root else None,
                "exists": source.exists(),
            }
        )

    return jobs


def needs_copy(source, dest):
    """True unless ``dest`` already exists with the same size as ``source``."""
    source, dest = Path(source), Path(dest)
    if not dest.exists():
        return True
    return source.stat().st_size != dest.stat().st_size


def copy_one(source, dest, dry_run=False):
    """Copy a single file, creating parent dirs. Return bytes copied (0 if skipped)."""
    source, dest = Path(source), Path(dest)
    if not needs_copy(source, dest):
        return 0
    if dry_run:
        return source.stat().st_size
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, dest)
    return dest.stat().st_size


def copy_job(job, dry_run=False):
    """Copy one manifest entry (file or whole directory). Return bytes copied."""
    source = Path(job["source"])
    dest_base = Path(job["dest"])
    copied = 0
    if source.is_file():
        return copy_one(source, dest_base, dry_run=dry_run)
    # Directory: dest points at <dest_root>/<relative>, mirror the tree inside it.
    for file_path, _ in iter_files(source):
        copied += copy_one(file_path, dest_base / file_path.relative_to(source), dry_run=dry_run)
    return copied


def report_plan(jobs):
    """Print the copy plan and return (total bytes of existing sources, missing jobs)."""
    total = 0
    missing = []
    print(f"{'TIER':<9} {'SIZE':>9}  PATH")
    print("-" * 78)
    for job in jobs:
        if not job["exists"]:
            missing.append(job)
            print(f"{job['tier']:<9} {'MISSING':>9}  {job['relative'].as_posix()}")
            continue
        size = path_size(job["source"])
        total += size
        print(f"{job['tier']:<9} {human_size(size):>9}  {job['relative'].as_posix()}")
        print(f"{'':<9} {'':>9}  -> {job['note']}")
    print("-" * 78)
    print(f"{'TOTAL':<9} {human_size(total):>9}")
    return total, missing


def run(dest_root, tiers, dry_run=False, project_root=PROJECT_ROOT):
    """Build the plan, print it, and perform the copies. Return bytes copied."""
    jobs = build_jobs(tiers, project_root=project_root, dest_root=dest_root)
    if not jobs:
        print("Nothing selected. Use --tier with one or more of: " + ", ".join(ALL_TIERS))
        return 0

    print(f"\nSource : {Path(project_root)}")
    print(f"Target : {Path(dest_root)}")
    print(f"Tiers  : {', '.join(tiers)}\n")
    _, missing = report_plan(jobs)

    if dry_run:
        print("\n[dry run] Nothing was copied.")
        return 0

    copied_total = 0
    to_copy = [job for job in jobs if job["exists"]]
    for index, job in enumerate(to_copy, start=1):
        print(f"\n[{index}/{len(to_copy)}] {job['relative'].as_posix()} ...", flush=True)
        copied = copy_job(job, dry_run=False)
        copied_total += copied
        print("    skipped (already present, same size)" if copied == 0 else f"    copied {human_size(copied)}")

    print(f"\nDone. Copied {human_size(copied_total)} to {Path(dest_root)}.")
    if missing:
        print(f"\nWARNING: {len(missing)} source(s) were missing and could not be copied:")
        for job in missing:
            print(f"  - {job['relative'].as_posix()}  ({job['note']})")
    print(
        "\nReminder: copy the code files too (the *.py / *.jl scripts, Project.toml,\n"
        "Manifest.toml, environment.yml) and create a .env in the new folder if you\n"
        "use the external datasets (see .env.example)."
    )
    return copied_total


def parse_args(argv=None):
    parser = argparse.ArgumentParser(
        description="Copy the datasets needed by the main.py pipeline to a new project folder.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument("--dest", required=True, help="Root of the new project folder.")
    parser.add_argument(
        "--tier",
        nargs="+",
        choices=ALL_TIERS,
        default=DEFAULT_TIERS,
        help=f"Which groups of files to copy (default: {' '.join(DEFAULT_TIERS)}).",
    )
    parser.add_argument("--dry-run", action="store_true", help="List what would be copied, copy nothing.")
    return parser.parse_args(argv)


if __name__ == "__main__":
    args = parse_args()
    run(Path(args.dest).expanduser(), args.tier, dry_run=args.dry_run)
    sys.exit(0)
